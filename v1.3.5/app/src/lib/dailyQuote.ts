/** 天数种子：UTC 天数取余数，保证同一天内稳定、跨天轮换。 */
function dayIndex(d: Date): number {
  const utc = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
  return Math.floor(utc / 86400000);
}

/** 取「今天」的每日一言（d 用于测试注入）。 */
export function dailyQuote(d: Date = new Date()): DailyQuote {
  return QUOTES[dayIndex(d) % QUOTES.length];
}
